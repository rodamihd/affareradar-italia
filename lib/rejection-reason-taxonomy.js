export function normalizeReasonToken(value) {
  return String(value || "")
    .trim()
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

export function canonicalRejectionReason(value) {
  const token = normalizeReasonToken(value);
  if (!token) return REJECTION_REASONS.UNSPECIFIED;
  return ALIASES[token] || (REJECTION_REASONS[token] ? token : token);
}

export function isKnownRejectionReason(value) {
  const canonical = canonicalRejectionReason(value);
  return Object.prototype.hasOwnProperty.call(REJECTION_REASONS, canonical);
}
